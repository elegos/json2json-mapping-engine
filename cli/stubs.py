"""`mapper stubs` (docs/ARCHITECTURE.md, §IDE setup for `.map.py` development).

Generates the schema-derived `.pyi`/`.py` artifacts, the `__mapping__`
IDE stub, and the IDE config files pointing at it.

**Known limitation**: `__mapping__.pyi` types `root`/`src`/`out` as `Any`
rather than per-mapping schema types. The architecture's own illustrative
stub example shows one specific mapping's concrete types (`OrderEvent`,
`Order`, `OrderLine`) — accurate for exactly one mapping at a time. Since a
project can have several `.map.py` files with different schema pairs, and
nothing in a plain IDE stub setup lets pyright/VS Code pick a different
`__mapping__.pyi` per open file, picking one mapping's types would be
actively misleading for every other file. Left as `Any` (matching the
documented no-schema behavior) until there's a real per-file selection
mechanism — plausibly an M6 (Tauri app) or per-directory-stub concern, not
a batch-CLI one.

**Caveat (discovered dogfooding this in the tool's own repo)**: `_merge_json`
preserves any *other keys* already in `pyrightconfig.json`, but a project
that currently configures pyright/basedpyright entirely via `pyproject.toml`
(`[tool.pyright]`/`[tool.basedpyright]`, no `pyrightconfig.json`) will have
that configuration silently stop applying the first time `mapper stubs`
runs — pyright ignores `pyproject.toml`'s section entirely whenever *any*
`pyrightconfig.json` exists, regardless of what keys it contains. Nothing
to fix here (the architecture doc specifies generating this file
unconditionally); just something for a project's own tooling setup to be
aware of before the first `mapper stubs` run.
"""

from __future__ import annotations

import json
from pathlib import Path

from compiler.schema_generator import generate_input_schemas, generate_output_schemas

SCHEMAS_INPUT_DIR = Path("schemas/input")
SCHEMAS_OUTPUT_DIR = Path("schemas/output")
STUBS_OUT_DIR = Path("generated/stubs")
DATACLASSES_OUT_DIR = Path("generated/dataclasses")
MAPPING_STUB_PATH = Path("build/python/stubs/__mapping__.pyi")
VSCODE_SETTINGS_PATH = Path(".vscode/settings.json")
PYRIGHTCONFIG_PATH = Path("pyrightconfig.json")

_MAPPING_STUB_TEXT = """\
# generated by `mapper stubs` — do not edit manually
from typing import Any

root: Any      # unchecked without a per-mapping stub selection mechanism
src: Any       # (see cli/stubs.py docstring) — reads are unchecked either way
out: Any
Null: type

def override(*, plsql: str = ..., **targets: str) -> Any: ...
def parallel(*, degree: int) -> Any: ...
def dataclass(cls: type) -> type: ...

__all__ = ["root", "src", "out", "Null", "override", "parallel", "dataclass"]
"""


def generate_stubs() -> dict[str, int]:
    written_in = generate_input_schemas(SCHEMAS_INPUT_DIR, STUBS_OUT_DIR)
    written_out = generate_output_schemas(SCHEMAS_OUTPUT_DIR, DATACLASSES_OUT_DIR)
    MAPPING_STUB_PATH.parent.mkdir(parents=True, exist_ok=True)
    MAPPING_STUB_PATH.write_text(_MAPPING_STUB_TEXT)
    _write_ide_config()
    return {"input_stubs": len(written_in), "output_dataclasses": len(written_out)}


def _write_ide_config() -> None:
    _merge_json(VSCODE_SETTINGS_PATH, {"python.analysis.stubPath": "build/python/stubs"})
    _merge_json(PYRIGHTCONFIG_PATH, {"stubPath": "build/python/stubs"})


def _merge_json(path: Path, updates: dict) -> None:
    existing: dict = {}
    if path.is_file():
        try:
            existing = json.loads(path.read_text())
        except json.JSONDecodeError:
            existing = {}
    existing.update(updates)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(existing, indent=2) + "\n")
